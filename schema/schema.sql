BEGIN;

CREATE TABLE donors (
    donor_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(100) NOT NULL,
    phone VARCHAR(20) NOT NULL,
    address TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE buyers (
    buyer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(100) NOT NULL,
    phone VARCHAR(20) NOT NULL,
    address TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE admins (
    admin_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL, -- store a password hash (e.g. bcrypt), never plaintext
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE donation_requests (
    request_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    donor_id INTEGER NOT NULL REFERENCES donors(donor_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    status VARCHAR(30) NOT NULL DEFAULT 'pending',
    notes TEXT,
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_donation_status CHECK (status IN ('pending', 'scheduled', 'picked_up', 'completed', 'cancelled'))
);

CREATE TABLE donated_foods (
    food_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id INTEGER NOT NULL REFERENCES donation_requests(request_id) ON UPDATE CASCADE ON DELETE CASCADE,
    food_name VARCHAR(100) NOT NULL,
    quantity NUMERIC(10,2) NOT NULL CHECK (quantity > 0),
    unit VARCHAR(30) NOT NULL,
    expiry_date DATE,
    description TEXT
);

CREATE TABLE pickup_schedules (
    schedule_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id INTEGER NOT NULL REFERENCES donation_requests(request_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    admin_id INTEGER NOT NULL REFERENCES admins(admin_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    pickup_date TIMESTAMPTZ NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'scheduled',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_pickup_schedule_status CHECK (status IN ('scheduled', 'confirmed', 'rescheduled', 'completed', 'cancelled'))
);

CREATE TABLE pickups (
    pickup_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id INTEGER NOT NULL UNIQUE REFERENCES pickup_schedules(schedule_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    picked_up_at TIMESTAMPTZ,
    status VARCHAR(30) NOT NULL DEFAULT 'pending',
    notes TEXT,
    CONSTRAINT chk_pickup_status CHECK (status IN ('pending', 'picked_up', 'failed', 'cancelled'))
);

CREATE TABLE food_suppliers (
    supplier_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_name VARCHAR(150) NOT NULL,
    email VARCHAR(100),
    phone VARCHAR(20),
    address TEXT,
    supplier_type VARCHAR(50),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE food_products (
    product_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id INTEGER NOT NULL REFERENCES admins(admin_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    supplier_id INTEGER REFERENCES food_suppliers(supplier_id) ON UPDATE CASCADE ON DELETE SET NULL,
    product_name VARCHAR(150) NOT NULL,
    description TEXT,
    price NUMERIC(12,2) NOT NULL CHECK (price >= 0),
    stock NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (stock >= 0),
    unit VARCHAR(30) NOT NULL,
    expiry_date DATE,
    status VARCHAR(30) NOT NULL DEFAULT 'available',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_product_status CHECK (status IN ('available', 'sold_out', 'unavailable', 'expired'))
);

CREATE TABLE orders (
    order_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    buyer_id INTEGER NOT NULL REFERENCES buyers(buyer_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    order_number VARCHAR(50) NOT NULL UNIQUE,
    delivery_address TEXT NOT NULL,
    total_amount NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (total_amount >= 0),
    delivery_fee NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (delivery_fee >= 0),
    order_status VARCHAR(30) NOT NULL DEFAULT 'pending',
    ordered_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_order_status CHECK (order_status IN ('pending', 'waiting_payment', 'paid', 'processing', 'shipped', 'completed', 'cancelled'))
);

CREATE TABLE order_items (
    order_item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL REFERENCES orders(order_id) ON UPDATE CASCADE ON DELETE CASCADE,
    product_id INTEGER NOT NULL REFERENCES food_products(product_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    quantity NUMERIC(10,2) NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
    subtotal NUMERIC(12,2) GENERATED ALWAYS AS (quantity * unit_price) STORED
);

CREATE TABLE payments (
    payment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL REFERENCES orders(order_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    payment_method VARCHAR(50) NOT NULL,
    amount NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
    payment_status VARCHAR(30) NOT NULL DEFAULT 'pending',
    transaction_reference VARCHAR(100) UNIQUE,
    paid_at TIMESTAMPTZ,
    CONSTRAINT chk_payment_status CHECK (payment_status IN ('pending', 'success', 'failed', 'expired', 'refunded'))
);

CREATE TABLE deliveries (
    delivery_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL UNIQUE REFERENCES orders(order_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    courier_name VARCHAR(100),
    courier_phone VARCHAR(20),
    delivery_address TEXT NOT NULL,
    delivery_status VARCHAR(30) NOT NULL DEFAULT 'pending',
    shipped_at TIMESTAMPTZ,
    delivered_at TIMESTAMPTZ,
    notes TEXT,
    CONSTRAINT chk_delivery_status CHECK (delivery_status IN ('pending', 'picked_up', 'delivering', 'delivered', 'failed', 'cancelled'))
);

-- PostgreSQL does not automatically index referencing (FK) columns.
CREATE INDEX idx_donation_requests_donor_id ON donation_requests(donor_id);
CREATE INDEX idx_donation_requests_status ON donation_requests(status);
CREATE INDEX idx_donated_foods_request_id ON donated_foods(request_id);
CREATE INDEX idx_pickup_schedules_request_id ON pickup_schedules(request_id);
CREATE INDEX idx_pickup_schedules_admin_id ON pickup_schedules(admin_id);
CREATE INDEX idx_pickup_schedules_pickup_date ON pickup_schedules(pickup_date);
CREATE INDEX idx_food_products_admin_id ON food_products(admin_id);
CREATE INDEX idx_food_products_supplier_id ON food_products(supplier_id);
CREATE INDEX idx_food_products_status ON food_products(status);
CREATE INDEX idx_orders_buyer_id ON orders(buyer_id);
CREATE INDEX idx_orders_status ON orders(order_status);
CREATE INDEX idx_order_items_order_id ON order_items(order_id);
CREATE INDEX idx_order_items_product_id ON order_items(product_id);
CREATE INDEX idx_payments_order_id ON payments(order_id);

COMMIT;
